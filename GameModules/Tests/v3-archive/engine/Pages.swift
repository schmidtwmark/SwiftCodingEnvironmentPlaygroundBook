import Foundation

/// Which page this is (hidden code only: `GameWiring(.walk)`).
public enum GamePage: Sendable, CaseIterable {
    // Part 1: Make It Move
    case walk, fall, jump, coins, score
    case sounds, sparkles, backgrounds, boing, heroMoves, stopwatch, lockedFlag
    // Part 2: Enemies
    case crab, bee, ghost, stomp
    case deathCounter, lives, starPower, fireballs, level2
    // Part 3: Your Game
    case design
}

extension GamePage {
    var info: PageInfo {
        // The scripts each page's starter shows (the panel warns when the real game had to use the
        // built-in version of one of them).
        let player: [ScriptName] = [.startPlayer, .updatePlayer]
        let coin = player + [.playerTouchedCoin]
        let score = coin + [.updateGame]
        let crab = score + [.startCrab, .updateCrab]
        let bee = crab + [.updateBee]
        let ghost = bee + [.updateGhost]
        let stomp = ghost + [.playerTouchedEnemy]
        let design = stomp + [.updateFrog, .playerTouchedFlag, .startGame, .playerGotHurt]
        switch self {
        // ---------- Part 1 (Monday) ----------
        case .walk:
            return PageInfo(title: "1. Walk", map: Levels.walk, checks: Checks.walk, scripts: player)
        case .fall:
            return PageInfo(title: "2. Fall", map: Levels.fall, checks: Checks.fall, scripts: player)
        case .jump:
            return PageInfo(title: "3. Jump", map: Levels.jump, checks: Checks.jump, scripts: player)
        case .coins:
            return PageInfo(title: "4. Coins", map: Levels.coins, checks: Checks.coins, lock: .coins, scripts: coin,
                            inspect: [.score])
        case .score:
            return PageInfo(title: "5. Show the Score", map: Levels.score, checks: Checks.score, scripts: score,
                            inspect: [.score])
        case .sounds:
            return PageInfo(title: "Extra: Sounds", map: Levels.sounds, checks: Checks.sounds, lock: .coins,
                            scripts: [.updatePlayer, .playerTouchedCoin], builtIns: .finished, inspect: [.score])
        case .sparkles:
            return PageInfo(title: "Extra: Sparkles", map: Levels.sparkles, checks: Checks.sparkles, lock: .coins,
                            scripts: [.updatePlayer, .playerTouchedCoin], builtIns: .finished, inspect: [.score])
        case .backgrounds:
            return PageInfo(title: "Extra: Backgrounds", map: Levels.backgrounds, checks: Checks.backgrounds, scripts: [],
                            builtIns: .finished, inspect: [.score])
        case .boing:
            return PageInfo(title: "Extra: Boing!", map: Levels.boing, checks: Checks.boing, scripts: [.playerTouchedSpring],
                            builtIns: .finished, inspect: [.score])
        case .heroMoves:
            return PageInfo(title: "Extra: Hero Moves", map: Levels.heroMoves, checks: Checks.heroMoves, scripts: [.updatePlayer],
                            builtIns: .finished, inspect: [.score])
        case .stopwatch:
            return PageInfo(title: "Extra: Stopwatch", map: Levels.stopwatch, checks: Checks.stopwatch,
                            scripts: [.updateGame, .playerTouchedFlag], builtIns: .finished, inspect: [.score, .gameTimer])
        case .lockedFlag:
            return PageInfo(title: "Extra: Locked Flag", map: Levels.lockedFlag, checks: Checks.lockedFlag,
                            scripts: [.playerTouchedFlag, .updateGame], builtIns: .finished, inspect: [.score])
        // ---------- Part 2 (Tuesday) ----------
        case .crab:
            return PageInfo(title: "6. Crab Patrol", map: Levels.crab, checks: Checks.crab, scripts: crab,
                            inspect: [.score])
        case .bee:
            return PageInfo(title: "7. Busy Bees", map: Levels.bee, checks: Checks.bee, scripts: bee,
                            inspect: [.score, .beeTimer])
        case .ghost:
            return PageInfo(title: "8. Ghost Chase", map: Levels.ghost, checks: Checks.ghost, scripts: ghost,
                            inspect: [.score])
        case .stomp:
            return PageInfo(title: "9. Stomp", map: Levels.stomp, checks: Checks.stomp, lock: .crabs, scripts: stomp,
                            inspect: [.score])
        case .deathCounter:
            return PageInfo(title: "Extra: Death Counter", map: Levels.deathCounter, checks: Checks.deathCounter,
                            scripts: [.playerGotHurt, .updateGame], builtIns: .finished, inspect: [.score, .deaths])
        case .lives:
            return PageInfo(title: "Extra: Lives and Game Over", map: Levels.lives, checks: Checks.lives,
                            scripts: [.startGame, .playerGotHurt, .updateGame], builtIns: .finished,
                            inspect: [.score, .deaths, .lives])
        case .starPower:
            return PageInfo(title: "Extra: Star Power", map: Levels.starPower, checks: Checks.starPower,
                            scripts: [.playerTouchedStar, .updatePlayer, .playerTouchedEnemy], builtIns: .finished,
                            inspect: [.score, .playerTimer])
        case .fireballs:
            return PageInfo(title: "Extra: Fireballs", map: Levels.fireballs, checks: Checks.fireballs,
                            scripts: [.updatePlayer, .updateFireball, .fireballTouchedEnemy], builtIns: .finished,
                            inspect: [.score])
        case .level2:
            return PageInfo(title: "Extra: Level 2", map: Levels.level2, checks: Checks.level2, scripts: [.playerTouchedFlag],
                            builtIns: .finished, inspect: [.score, .levelNumber])
        // ---------- Part 3 ----------
        case .design:
            return PageInfo(title: "10. Design Your Own Game", map: Levels.design, scripts: design,
                            inspect: [.score, .deaths, .lives, .gameTimer])
        }
    }
}

