import Foundation

/// Which page this is (hidden code only: `GameWiring(.walk)`). The book is one chain: every page
/// starts with all the code of the pages before it, so the cases are in page order.
public enum GamePage: Sendable, CaseIterable {
    // Part 1: Moving
    case walk, fall, jump, coyote
    // Part 2: Coins and Effects
    case coins, score, sounds, sparkles
    // Part 3: Enemies
    case crab, bee, ghost, stomp
    // Part 4: Looks
    case heroMoves, backgrounds
    // Part 5: Power-ups
    case boing, starPower, fireballs
    // Part 6: Rules of the Game
    case stopwatch, deathCounter, lives, lockedFlag, level2
    // Part 7: Your Game
    case design
}

extension GamePage {
    var info: PageInfo {
        // Every function each page's starter shows: the whole book so far (the panel warns when the
        // real game had to use the do-nothing built-in version of one of them).
        let moving: [FunctionName] = [.startPlayer, .updatePlayer, .playerTouchedFlag]
        let jumping = moving + [.playerGotHurt]
        let coins = jumping + [.playerTouchedCoin]
        let score = coins + [.updateGame]
        let crab = score + [.startCrab, .updateCrab, .playerTouchedEnemy]
        let bee = crab + [.updateBee]
        let ghost = bee + [.updateGhost]
        let spring = ghost + [.playerTouchedSpring]
        let star = spring + [.playerTouchedStar]
        let fire = star + [.updateFireball, .fireballTouchedEnemy]
        let lives = fire + [.startGame]
        switch self {
        // ---------- Part 1: Moving ----------
        case .walk:
            return PageInfo(title: "1. Walk", map: Levels.walk, checks: Checks.walk, functions: moving)
        case .fall:
            return PageInfo(title: "2. Fall", map: Levels.fall, checks: Checks.fall, functions: moving)
        case .jump:
            return PageInfo(title: "3. Jump", map: Levels.jump, checks: Checks.jump, functions: jumping)
        case .coyote:
            return PageInfo(title: "4. Coyote Time", map: Levels.coyote, checks: Checks.coyote, functions: jumping,
                            inspect: [.lastJump])
        // ---------- Part 2: Coins and Effects ----------
        case .coins:
            return PageInfo(title: "5. Coins", map: Levels.coins, checks: Checks.coins, lock: .coins, functions: coins,
                            inspect: [.score])
        case .score:
            return PageInfo(title: "6. Show the Score", map: Levels.score, checks: Checks.score, functions: score,
                            inspect: [.score])
        case .sounds:
            return PageInfo(title: "7. Sounds", map: Levels.sounds, checks: Checks.sounds, lock: .coins, functions: score,
                            inspect: [.score])
        case .sparkles:
            return PageInfo(title: "8. Sparkles", map: Levels.sparkles, checks: Checks.sparkles, lock: .coins, functions: score,
                            inspect: [.score])
        // ---------- Part 3: Enemies ----------
        case .crab:
            return PageInfo(title: "9. Crab Patrol", map: Levels.crab, checks: Checks.crab, functions: crab,
                            inspect: [.score])
        case .bee:
            return PageInfo(title: "10. Busy Bees", map: Levels.bee, checks: Checks.bee, functions: bee,
                            inspect: [.score, .beeTimer])
        case .ghost:
            return PageInfo(title: "11. Ghost Chase", map: Levels.ghost, checks: Checks.ghost, functions: ghost,
                            inspect: [.score])
        case .stomp:
            return PageInfo(title: "12. Stomp", map: Levels.stomp, checks: Checks.stomp, lock: .crabs, functions: ghost,
                            inspect: [.score])
        // ---------- Part 4: Looks ----------
        case .heroMoves:
            return PageInfo(title: "13. Hero Moves", map: Levels.heroMoves, checks: Checks.heroMoves, functions: ghost,
                            inspect: [.score])
        case .backgrounds:
            return PageInfo(title: "14. Backgrounds", map: Levels.backgrounds, checks: Checks.backgrounds, functions: ghost,
                            inspect: [.score])
        // ---------- Part 5: Power-ups ----------
        case .boing:
            return PageInfo(title: "15. Boing!", map: Levels.boing, checks: Checks.boing, functions: spring,
                            inspect: [.score])
        case .starPower:
            return PageInfo(title: "16. Star Power", map: Levels.starPower, checks: Checks.starPower, functions: star,
                            inspect: [.score, .playerTimer])
        case .fireballs:
            return PageInfo(title: "17. Fireballs", map: Levels.fireballs, checks: Checks.fireballs, functions: fire,
                            inspect: [.score])
        // ---------- Part 6: Rules of the Game ----------
        case .stopwatch:
            return PageInfo(title: "18. Stopwatch", map: Levels.stopwatch, checks: Checks.stopwatch, functions: fire,
                            inspect: [.score, .gameTimer])
        case .deathCounter:
            return PageInfo(title: "19. Death Counter", map: Levels.deathCounter, checks: Checks.deathCounter, functions: fire,
                            inspect: [.score, .deaths])
        case .lives:
            return PageInfo(title: "20. Lives and Game Over", map: Levels.lives, checks: Checks.lives, functions: lives,
                            inspect: [.score, .deaths, .lives])
        case .lockedFlag:
            return PageInfo(title: "21. Locked Flag", map: Levels.lockedFlag, checks: Checks.lockedFlag, functions: lives,
                            inspect: [.score])
        case .level2:
            return PageInfo(title: "22. Level 2", map: Levels.level2, checks: Checks.level2, functions: lives,
                            inspect: [.score, .levelNumber])
        // ---------- Part 7: Your Game ----------
        case .design:
            return PageInfo(title: "23. Design Your Own Game", map: Levels.design, functions: lives,
                            inspect: [.score, .deaths, .lives, .gameTimer])
        }
    }
}

